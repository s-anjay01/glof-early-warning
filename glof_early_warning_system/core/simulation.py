"""
Scenario Simulation Engine for GLOF Outburst Triggers.
Simulates:
1. Rock / Ice Avalanche displacement wave (impulse tsunami wave)
2. Cloudburst / Extreme Runoff Influx
3. Progressive Moraine Dam Breach Failure
"""

import math
from typing import Dict, Any
from .hydrology import (
    calculate_costa_peak_discharge,
    calculate_froehlich_peak_discharge,
    calculate_huggel_peak_discharge,
    generate_outburst_hydrograph,
    simulate_downstream_propagation
)


def simulate_avalanche_trigger(
    lake: Dict[str, Any],
    avalanche_volume_m3: float = 1_500_000.0,
    impact_angle_deg: float = 45.0
) -> Dict[str, Any]:
    """
    Simulates displacement wave generated by ice/rock avalanche entering lake (Heller & Hager impulse wave theory).
    Calculates initial wave height, overtopping volume, and potential dam crest breach.
    """
    lake_area_m2 = float(lake.get("lake_area_km2", 1.0)) * 1_000_000.0
    freeboard_m = float(lake.get("freeboard_m", 15.0))
    lake_depth_m = float(lake.get("max_depth_m", 50.0))
    lake_volume_m3 = float(lake.get("lake_volume_mcm", 10.0)) * 1_000_000.0
    dam_height_m = float(lake.get("dam_height_m", 45.0))

    # Simplified impulse wave height at impact point:
    # H_wave ~ 0.28 * depth * (V_avalanche / (depth^3)) ^ 0.35 * sin(angle)
    ratio = avalanche_volume_m3 / max(100.0, (lake_depth_m ** 3))
    wave_height_m = 0.35 * lake_depth_m * (ratio ** 0.32) * math.sin(math.radians(impact_angle_deg))
    wave_height_m = max(2.0, min(65.0, wave_height_m))

    # Wave reaches moraine dam after attenuation across lake length
    lake_fetch_m = math.sqrt(lake_area_m2) * 1.4
    decay = 1.0 / (1.0 + 0.0006 * lake_fetch_m)
    dam_wave_height_m = wave_height_m * decay

    # Overtopping calculation
    overtopping_height_m = max(0.0, dam_wave_height_m - freeboard_m)
    will_overtop = overtopping_height_m > 0.0

    if will_overtop:
        # Breached fraction depends on overtopping magnitude and dam height
        breach_depth_m = min(dam_height_m * 0.85, freeboard_m + (overtopping_height_m * 1.5))
        drained_volume_pct = min(75.0, max(15.0, (breach_depth_m / dam_height_m) * 60.0))
        drained_volume_m3 = lake_volume_m3 * (drained_volume_pct / 100.0)
    else:
        breach_depth_m = 0.0
        drained_volume_pct = 0.0
        drained_volume_m3 = 0.0

    # Hydrological breach discharge
    if drained_volume_m3 > 0:
        costa_q = calculate_costa_peak_discharge(drained_volume_m3, breach_depth_m)
        froehlich_q = calculate_froehlich_peak_discharge(drained_volume_m3, breach_depth_m)
        huggel_q = calculate_huggel_peak_discharge(drained_volume_m3, breach_depth_m)
        peak_q = (costa_q * 0.45 + froehlich_q * 0.40 + huggel_q * 0.15)
    else:
        costa_q = froehlich_q = huggel_q = peak_q = 0.0

    hydrograph = generate_outburst_hydrograph(peak_q, drained_volume_m3)
    downstream_impact = simulate_downstream_propagation(
        peak_q, lake.get("downstream_elements", [])
    )

    return {
        "trigger_type": "Ice / Rock Avalanche Displacement Wave",
        "avalanche_volume_m3": avalanche_volume_m3,
        "initial_wave_height_m": round(wave_height_m, 2),
        "wave_at_dam_crest_m": round(dam_wave_height_m, 2),
        "freeboard_m": freeboard_m,
        "overtopping_height_m": round(overtopping_height_m, 2),
        "breach_occurred": will_overtop,
        "estimated_breach_depth_m": round(breach_depth_m, 1),
        "water_released_mcm": round(drained_volume_m3 / 1_000_000.0, 2),
        "lake_volume_drained_pct": round(drained_volume_pct, 1),
        "peak_discharge_m3s": round(peak_q, 1),
        "models": {
            "Costa_1985": round(costa_q, 1),
            "Froehlich_1995": round(froehlich_q, 1),
            "Huggel_2002": round(huggel_q, 1)
        },
        "hydrograph": hydrograph,
        "downstream_impact": downstream_impact
    }


def simulate_moraine_breach(
    lake: Dict[str, Any],
    breach_width_m: float = 60.0,
    breach_depth_fraction: float = 0.60
) -> Dict[str, Any]:
    """
    Direct moraine dam failure simulation with customizable breach dimensions.
    """
    lake_volume_m3 = float(lake.get("lake_volume_mcm", 10.0)) * 1_000_000.0
    dam_height_m = float(lake.get("dam_height_m", 50.0))

    breach_depth_m = dam_height_m * max(0.1, min(0.95, breach_depth_fraction))
    drained_pct = min(85.0, (breach_depth_m / dam_height_m) * 70.0)
    drained_volume_m3 = lake_volume_m3 * (drained_pct / 100.0)

    costa_q = calculate_costa_peak_discharge(drained_volume_m3, breach_depth_m)
    froehlich_q = calculate_froehlich_peak_discharge(drained_volume_m3, breach_depth_m)
    huggel_q = calculate_huggel_peak_discharge(drained_volume_m3, breach_depth_m)

    peak_q = (costa_q * 0.45 + froehlich_q * 0.40 + huggel_q * 0.15)

    hydrograph = generate_outburst_hydrograph(peak_q, drained_volume_m3)
    downstream_impact = simulate_downstream_propagation(
        peak_q, lake.get("downstream_elements", [])
    )

    return {
        "trigger_type": "Moraine Dam Piping / Crest Failure",
        "breach_width_m": breach_width_m,
        "breach_depth_m": round(breach_depth_m, 1),
        "water_released_mcm": round(drained_volume_m3 / 1_000_000.0, 2),
        "lake_volume_drained_pct": round(drained_pct, 1),
        "peak_discharge_m3s": round(peak_q, 1),
        "models": {
            "Costa_1985": round(costa_q, 1),
            "Froehlich_1995": round(froehlich_q, 1),
            "Huggel_2002": round(huggel_q, 1)
        },
        "hydrograph": hydrograph,
        "downstream_impact": downstream_impact
    }
